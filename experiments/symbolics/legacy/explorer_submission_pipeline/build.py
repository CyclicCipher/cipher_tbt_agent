"""Build the Kaggle submission from `explorer.py`: `my_agent.py` (the explorer plus the framework adapter, one file)
and `notebook/submission.ipynb` + `notebook/kernel-metadata.json`.

The notebook has the four cells of Kaggle's official sample (as in github.com/arcprize/ARC-AGI-3-Kaggle-Starter):
install the offline `arc-agi` wheels; write my_agent.py; in the competition rerun, register MyAgent with the
ARC-AGI-3-Agents framework and run it against the hidden-game gateway; otherwise write a dummy submission.parquet.

    venv312/Scripts/python.exe experiments/symbolics/arc_agent/kaggle/build.py [kaggle-username]

Then (needs your Kaggle API token; see SUBMIT.md): kaggle kernels push -p experiments/symbolics/arc_agent/kaggle/notebook
"""
import json
import sys
from pathlib import Path
from textwrap import dedent

HERE = Path(__file__).resolve().parent
MAX_ACTIONS = 3000          # per game; the score counts only completed levels, so more actions never lower it

ADAPTER = '''

# ---- the ARC-AGI-3-Agents framework adapter (added by build.py) ------------------------------------------------------
from arcengine import GameAction, GameState  # noqa: E402
from agents.agent import Agent  # noqa: E402


class MyAgent(Agent):
    """The framework runs one MyAgent per game, each in its own thread."""
    MAX_ACTIONS = %d

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.core = Explorer(self.game_id)
        self.pending = None

    def is_done(self, frames, latest_frame):
        return latest_frame.state is GameState.WIN

    def choose_action(self, frames, latest_frame):
        a, data = self.core.act(latest_frame)
        self.pending = data
        return GameAction.from_id(a)

    def do_action_request(self, action):
        """The click's coordinates are passed per agent, not stored on the shared GameAction enum (several games run
        at once in threads, so the enum's own data could be overwritten by another game's click)."""
        raw = self.arc_env.step(action, data=self.pending or {})
        return self._convert_raw_frame_data(raw)
''' % MAX_ACTIONS


def code(src):
    return {"cell_type": "code", "metadata": {"trusted": True}, "outputs": [], "execution_count": None, "source": src}


def build(username):
    agent = (HERE / "explorer.py").read_text(encoding="utf-8") + ADAPTER
    (HERE / "my_agent.py").write_text(agent, encoding="utf-8")
    run = dedent("""\
        import os

        if os.getenv('KAGGLE_IS_COMPETITION_RERUN'):
            !curl --fail --retry 999 --retry-all-errors --retry-delay 5 --retry-max-time 600 http://gateway:8001/api/games
            !cp -r /kaggle/input/competitions/arc-prize-2026-arc-agi-3/ARC-AGI-3-Agents /kaggle/working/ARC-AGI-3-Agents
            !cp /tmp/my_agent.py /kaggle/working/ARC-AGI-3-Agents/agents/templates/my_agent.py
            with open('/kaggle/working/ARC-AGI-3-Agents/agents/__init__.py', 'w') as f:
                f.write(\"\"\"from typing import Type
        from dotenv import load_dotenv
        from .agent import Agent, Playback
        from .swarm import Swarm
        from .templates.random_agent import Random
        from .templates.my_agent import MyAgent

        load_dotenv()

        AVAILABLE_AGENTS: dict[str, Type[Agent]] = {
            'random': Random,
            'myagent': MyAgent,
        }
        \"\"\")
            with open('/kaggle/working/ARC-AGI-3-Agents/.env', 'w') as f:
                f.write(\"\"\"SCHEME=http
        HOST=gateway
        PORT=8001
        ARC_API_KEY=test-key-123
        ARC_BASE_URL=http://gateway:8001/
        OPERATION_MODE=online
        ENVIRONMENTS_DIR=
        RECORDINGS_DIR=/kaggle/working/server_recording
        \"\"\")
            !cd /kaggle/working/ARC-AGI-3-Agents && MPLBACKEND=agg python main.py --agent myagent
        """)
    dummy = dedent("""\
        import os
        if not os.getenv('KAGGLE_IS_COMPETITION_RERUN'):
            import pandas as pd
            pd.DataFrame(data=[['1_0', '1', True, 1]], columns=['row_id', 'game_id', 'end_of_game', 'score']
                         ).to_parquet('/kaggle/working/submission.parquet', index=False)
        """)
    nb = {"metadata": {"kernelspec": {"language": "python", "display_name": "Python 3", "name": "python3"},
                       "language_info": {"name": "python", "mimetype": "text/x-python", "file_extension": ".py",
                                         "pygments_lexer": "ipython3"},
                       "kaggle": {"accelerator": "none", "isInternetEnabled": False, "isGpuEnabled": False,
                                  "language": "python", "sourceType": "notebook"}},
          "nbformat_minor": 4, "nbformat": 4,
          "cells": [{"cell_type": "markdown", "metadata": {},
                     "source": "# ARC-AGI-3 explorer\n\nGenerated by `build.py` from `explorer.py`; do not edit here."},
                    code("!pip install --no-index --find-links /kaggle/input/competitions/arc-prize-2026-arc-agi-3/arc_agi_3_wheels arc-agi python-dotenv"),
                    code("%%writefile /tmp/my_agent.py\n" + agent), code(run), code(dummy)]}
    out = HERE / "notebook"
    out.mkdir(exist_ok=True)
    (out / "submission.ipynb").write_text(json.dumps(nb, indent=1), encoding="utf-8")
    meta = {"id": f"{username}/arc3-explorer", "title": "ARC3 Explorer", "code_file": "submission.ipynb",
            "language": "python", "kernel_type": "notebook", "is_private": True, "enable_gpu": False,
            "enable_tpu": False, "enable_internet": False, "keywords": [], "dataset_sources": [], "kernel_sources": [],
            "competition_sources": ["arc-prize-2026-arc-agi-3"], "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote my_agent.py ({len(agent.splitlines())} lines) and notebook/ for {username}")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "REPLACE_WITH_YOUR_KAGGLE_USERNAME")
