def check(games, actions):
    """The bundle, written to a fresh folder, playing local games through the adapter."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "arc_agent").mkdir()
        for name, text in sources().items():
            (tmp / "arc_agent" / name).write_text(text, encoding="utf-8")
        (tmp / "my_agent.py").write_text(ADAPTER % (tmp.as_posix(), MAX_ACTIONS), encoding="utf-8")
        (tmp / "agents").mkdir()
        (tmp / "agents" / "__init__.py").write_text("", encoding="utf-8")
        (tmp / "agents" / "agent.py").write_text(STANDIN, encoding="utf-8")
        (tmp / "play.py").write_text(PLAY, encoding="utf-8")
        envs = AGENT.parents[2] / "environment_files"
        env = dict(os.environ, PYTHONPATH=str(tmp), MPLCONFIGDIR=str(tmp))   # only the bundle on the path
        subprocess.run([sys.executable, str(tmp / "play.py"), str(envs), games, str(actions)], cwd=tmp, check=True,
                       env=env)


if __name__ == "__main__":
    args = sys.argv[1:]
    if args[:1] == ["--check"]:
        check(args[1] if len(args) > 1 else "ar25,ls20", int(args[2]) if len(args) > 2 else 60)
    else:
        build(args[0] if args else "REPLACE_WITH_YOUR_KAGGLE_USERNAME")
