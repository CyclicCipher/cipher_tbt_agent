"""E7 — the anatomy pass: read the network ZipLearner wrote and ask what it became.

Everything ZipLearner writes is a matrix with a name, so this is reading, not probing. Four parts:
  1. the two-layer network of E2 on two tasks: every written matrix, its structure, parameters, evidence, exceptions,
     and its price against the table it replaced;
  2. the algebra of E3's library: the 17 named position permutations -- the group they generate inside the 720
     permutations of six positions, which items are products of two others, the smallest generating set, each item
     written in terms of the domain's five primitives, and the library priced flat (entries) against generators +
     words (the first concrete instance of OPEN-5, structures of structures);
  3. the blocks of E6 on one stream, and the price of merging the two shift blocks into one template with a
     per-context offset (rule 3's merge, as arithmetic);
  4. a figure: the written matrices as heatmaps and the gradient arm's learned routes (E0) as a heatmap.

    python experiments/ziplearn/anatomy.py       (seconds, CPU) -> runs/e7/anatomy.json, anatomy.png
"""
