# ── permutations as "output position j reads input position pi[j]" ─────────────────────────────────────────────────
def then(p, q):
    """First p, then q: z[j] = y[q[j]] = x[p[q[j]]]."""
    return tuple(p[q[j]] for j in range(len(p)))


def inverse(p):
    inv = [0] * len(p)
    for j, i in enumerate(p):
        inv[i] = j
    return tuple(inv)


def closure(gens):
    """The group generated by these permutations under composition (finite, so composition alone suffices)."""
    ident = tuple(range(len(next(iter(gens)))))
    seen = {ident}
    frontier = deque([ident])
    while frontier:
        g = frontier.popleft()
        for s in gens:
            h = then(g, s)
            if h not in seen:
                seen.add(h)
                frontier.append(h)
    return seen


def words(gens, targets):
    """Shortest word (as a list of generator indices) reaching each target, by breadth-first search."""
    ident = tuple(range(len(gens[0])))
    best = {ident: []}
    frontier = deque([ident])
    targets = set(targets)
    while frontier and not targets <= set(best):
        g = frontier.popleft()
        for i, s in enumerate(gens):
            h = then(g, s)
            if h not in best:
                best[h] = best[g] + [i]
                frontier.append(h)
    return {t: best.get(t) for t in targets}


def part2_library(named, prim_names, prims):
    ident = tuple(range(L))
    named = [tuple(p) for p in named]
    G = closure(set(named) | {ident})
    G_prims = closure(set(prims.values()) | {ident})
    # each named item in terms of the five primitives (single, or first p then q)
    in_prims = {}
    for c in named:
        hits = [n for n, p in prims.items() if p == c]
        if not hits:
            hits = [f"{a}∘{b}" for a, b in itertools.product(prim_names, repeat=2) if then(prims[a], prims[b]) == c]
        in_prims[c] = hits
    # which named items are products of two OTHER named items
    products = {}
    for c in named:
        products[c] = [(a, b) for a in named for b in named if a != c and b != c and then(a, b) == c]
    # smallest generating subset of the named items whose closure contains all of them
    gen_set = None
    for k in range(1, len(named) + 1):
        for sub in itertools.combinations(named, k):
            if set(named) <= closure(set(sub) | {ident}):
                gen_set = list(sub)
                break
        if gen_set:
            break
    w = words(gen_set, [c for c in named if c not in gen_set])
    bits_entry = math.log2(math.factorial(L))
    flat = len(named) * bits_entry
    gens_bits = len(gen_set) * bits_entry
    word_bits = sum(len(w[c]) * math.log2(len(gen_set)) + math.log2(1 + len(w[c])) for c in w)
    return dict(n_named=len(named), group_order=len(G), group_order_from_primitives=len(G_prims),
                in_primitives={str(c): v for c, v in in_prims.items()},
                n_products_of_two_others=sum(1 for c in named if products[c]),
                products_example={str(c): [f"{a} then {b}" for a, b in products[c][:2]] for c in named if products[c]},
                generating_set=[list(g) for g in gen_set], generating_set_in_primitives=[in_prims[g] for g in gen_set],
                words={str(c): [gen_set.index(gen_set[i]) for i in w[c]] for c in w},
                max_word_length=max(len(v) for v in w.values()) if w else 0,
                bits_flat=flat, bits_generators_plus_words=gens_bits + word_bits, bits_per_entry=bits_entry)


def part1_two_layer(task, rng, K=8):
    out = {}
    for pair in ((1, 6), (4, 5)):                                       # rot_left∘negate, swap_halves∘inc
        x = rng.integers(0, task.V, (K, L))
        y = task.apply(torch.tensor(x), pair).numpy()
        learner = TwoLayer(L, task.V)
        for k in range(K):
            learner.observe_demo(x[k], y[k])
        name, (a, b), pos = learner.best()
        P = np.zeros((L, L))
        for j in range(L):
            P[j, pos.pi(j)] = 1
        W = np.zeros((task.V, task.V))
        for v in range(task.V):
            W[v, (a * v + b) % task.V] = 1
        # prices: the kept description vs a table for each layer (a table over 6 positions is 6 entries of log2(6);
        # a table over values, V entries of log2 V; both plus the pairs seen)
        out[task.describe(pair)] = dict(
            position=dict(structure=pos.name, pi=[pos.pi(j) for j in range(L)], matrix=P.tolist(), cost_bits=round(pos.cost, 2),
                          n_right=pos.n_right, n_wrong=pos.n_wrong),
            value=dict(structure=name, a=a, b=b, matrix=W.tolist()),
            total_price_bits=round(learner.best_price[0] if hasattr(learner, "best_price") else 0, 2))
    return out


def part3_blocks(rng, V=11):
    RULES = {"A": (1, 3), "B": (1, 5), "C": (2, 1)}
    layer = ContinualLayer(V)
    for name in ["A", "B", "C", "A"]:
        a, b = RULES[name]
        for _ in range(40):
            x = int(rng.integers(V))
            layer.observe(x, (a * x + b) % V)
    blocks = []
    for blk in layer.blocks:
        s = blk["layer"].keep()
        blocks.append(dict(structure=s.name, params={k: getattr(s, k) for k in ("a", "b") if hasattr(s, k)},
                           evidence=blk["n"], exception_rate=round(s.rate, 3), price_bits=round(blk["layer"].price(s), 2),
                           table_price_bits=round(blk["layer"].price(next(t for t in blk["layer"].structs if t.name == "table")), 2),
                           matrix=s.write().tolist()))
    # rule 3's merge as arithmetic: two shift blocks as one "shift with a per-context offset"
    shifts = [b for b in blocks if b["structure"] == "shift"]
    merge = None
    if len(shifts) == 2:
        two_blocks = sum(b["price_bits"] for b in shifts) + 2 * math.log2(len(blocks))
        template = math.log2(len(blocks)) + math.log2(3) + 2 * math.log2(V) + sum(
            b["price_bits"] - math.log2(V) - math.log2(5) for b in shifts)   # one name, one structure, two offsets, the flags
        merge = dict(two_blocks_bits=round(two_blocks, 2), one_template_bits=round(template, 2))
    return dict(blocks=blocks, merge_arithmetic=merge, total_bits=round(layer.total_bits(), 2))


def figure(two_layer, routes, out):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 4, figsize=(15, 3.6))
    (t1, d1), (t2, d2) = list(two_layer.items())[:2]
    for ax, (t, d) in zip(axes[:2], ((t1, d1), (t2, d2))):
        ax.imshow(np.array(d["position"]["matrix"]), cmap="Greys", vmin=0, vmax=1)
        ax.set_title(f"{t}\nlayer 1: {d['position']['structure']}", fontsize=9)
        ax.set_xlabel("reads input position")
        ax.set_ylabel("output position")
    ax = axes[2]
    ax.imshow(np.array(d2["value"]["matrix"]), cmap="Greys", vmin=0, vmax=1)
    ax.set_title(f"{t2}\nlayer 2: {d2['value']['structure']} a={d2['value']['a']} b={d2['value']['b']}", fontsize=9)
    ax.set_xlabel("output digit")
    ax.set_ylabel("input digit")
    ax = axes[3]
    if routes:
        names = list(routes)
        M = np.full((len(names), 4), np.nan)
        for i, n in enumerate(names):
            M[i, :len(routes[n])] = routes[n]
        im = ax.imshow(M, cmap="viridis", vmin=0, vmax=1, aspect="auto")
        ax.set_yticks(range(len(names)))
        ax.set_yticklabels([n.replace("blocks.", "L").replace(".res_", " before ") for n in names], fontsize=7)
        ax.set_xticks(range(4))
        ax.set_xticklabels(["embedding", "block 1", "block 2", "block 3 / partial"], fontsize=7, rotation=20)
        ax.set_title("gradient arm (E0, RoPE + attention residuals):\nlearned routes, mean weight per source", fontsize=9)
        plt.colorbar(im, ax=ax, fraction=0.046)
    plt.tight_layout()
    plt.savefig(out / "anatomy.png", dpi=130)


