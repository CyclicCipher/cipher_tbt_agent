"""COST-TO-GO ON A CANONICAL STATE: the DeepCubeA setting, reached properly.

WHY THE FIRST ATTEMPT FELL SHORT. `costtogo.py` learned a distance heuristic from BEHAVIOUR — interleaved
`[current, goal]` demonstration pairs — and it was weak (depth-stratified exact 0.276 against a 0.167 floor, MAE 1.38) and
lost to a free hand-coded Hamming heuristic on cost-per-success (98.8 expansions against 38.5). The diagnosis was that
DeepCubeA has a CANONICAL STATE — the cube's 54 stickers *are* the input and distance is a function of them — whereas that
version made the network first infer a transformation from a behavioural sample and only then estimate its distance.

WHAT MAKES THE CANONICAL VERSION POSSIBLE. Two earlier results combine:
  * `localise.py` showed the composed map is EXACTLY recoverable from a handful of demonstrations, so the transformation
    itself is available, not just its behaviour.
  * Every element of this group is a position permutation composed with a value map, and the value maps are exactly
    `Aff(Z5)` = 10 elements (generated by `add_k` and `negate`). So a group element IS `(idx, vmp)` — **11 tokens**, a
    6-permutation and a 5-value map. Recovery brute-forces the 10 affine maps and matches columns; exact, and verified
    below rather than assumed.

AND THE FORMULATION GETS BETTER, not just the input. Searching for a factorisation of `f`, if `h` is the program applied
so far then the residual is `r = f . h^-1`, and applying one more primitive `p` right-multiplies it: `r' = r . p^-1`. So the
search is a walk on the Cayley graph from `f` to the identity, and **the heuristic is a function of ONE group element —
its distance to the identity — rather than of a (state, goal) pair.** That is exactly DeepCubeA's state -> cost-to-go, on
an 11-token canonical state, with exact labels from the BFS table.

WHAT WOULD MAKE THIS A NEGATIVE RESULT. If the canonical heuristic is no better than the behavioural one, then the extra
inference step was not the problem and the shortfall is compute or the target itself. If it is much better but still loses
to the free hand-coded baseline, the route works in principle and not at this scale. Both are reportable; the baselines are
what decide it:
  * `zero`         — uniform-cost search, the uninformed floor.
  * `misplaced`    — non-fixed points of the permutation plus one if the value map is not the identity. Hand-coded, free,
                     and the canonical analogue of the Hamming baseline that beat the learned heuristic last time.
  * `learned`      — the network on the canonical state.

Held-out transformations never appear in heuristic training, and search queries the heuristic on them constantly.

Usage:  python experiments/transformers/canonical.py
"""
from __future__ import annotations

import argparse
import collections
import heapq
import math
import time

import torch
import torch.nn.functional as F

from bigroup import NAMES, apply_prog, cayley, compile_progs, stratify
from h1_lid import L, V, Model

MAXM = 5
IDX0, VMP0 = 0, L                      # token blocks: idx values 0..L-1, vmp values L..L+V-1
DIST0 = L + V                          # distance classes after them
N_VOCAB = L + V + MAXM + 1


def act(tab, s):
    """T_(idx,vmp)(s)[j] = vmp[s[idx[j]]] — the canonical action, matching `compile_progs`."""
    idx, vmp = tab
    return vmp[s.gather(-1, idx.expand(*s.shape[:-1], L))]


def compose(A, B):
    """Tables of "apply A, then B". T_B(T_A(s))[j] = vmp_B[vmp_A[s[idx_A[idx_B[j]]]]]."""
    return (A[0][B[0]], B[1][A[1]])


def inverse(A):
    """T_A^-1: invert both tables. Asserted against the action in main()."""
    return (torch.argsort(A[0]), torch.argsort(A[1]))


def recover(x, y, affines, dev):
    """The transformation carrying x to y, in CANONICAL form, recovered exactly from demonstrations. Brute-forces the 10
    affine value maps; for each, applies it to the inputs and looks for a column permutation matching the outputs. Returns
    None if no candidate is consistent across every demonstration (which is the honest failure signal)."""
    for v in affines:
        z = v[x]                                                      # the affine value map, applied elementwise
        idx = []
        ok = True
        for j in range(L):
            cand = [i for i in range(L) if bool((z[:, i] == y[:, j]).all())]
            if not cand:
                ok = False
                break
            idx.append(cand[0])
        if ok:
            t = (torch.tensor(idx, device=dev), v)
            if torch.equal(act(t, x), y):
                return t
    return None


def make(B, tabs, lens, dev, g, fixed=None):
    """Canonical state tokens, then the exact distance class."""
    idx_t, vmp_t = tabs
    n = idx_t.shape[0]
    sel = (torch.full((B,), fixed, dtype=torch.long, device=dev) if fixed is not None
           else torch.randint(0, n, (B,), generator=g, device=dev))
    return torch.cat([idx_t[sel] + IDX0, vmp_t[sel] + VMP0, (DIST0 + lens[sel])[:, None]], dim=1)


def tokens_of(states, dev):
    """A batch of canonical states as tokens, for querying the heuristic."""
    return torch.cat([torch.stack([s[0] for s in states]) + IDX0,
                      torch.stack([s[1] for s in states]) + VMP0], dim=1)


@torch.no_grad()
def h_learned(model, states, dev):
    p = model(tokens_of(states, dev))[:, -1, DIST0:DIST0 + MAXM + 1].softmax(-1)
    return (p * torch.arange(MAXM + 1, device=dev, dtype=p.dtype)).sum(-1).tolist()


def h_misplaced(states, dev):
    """Free hand-coded baseline: non-fixed points of the permutation, plus one if the value map is not the identity."""
    ar_L = torch.arange(L, device=dev)
    ar_V = torch.arange(V, device=dev)
    return [float((s[0] != ar_L).sum() + (0 if bool((s[1] == ar_V).all()) else 1)) for s in states]


def h_zero(states, _dev):
    return [0.0] * len(states)


def best_first(target, inv_tabs, hfn, ident, dev, lam, cap):
    """Walk the Cayley graph from the target transformation to the identity, right-multiplying by primitive inverses.
    The heuristic scores all children in one batch."""
    key = lambda t: (tuple(t[0].tolist()), tuple(t[1].tolist()))
    ik = key(ident)
    h0 = hfn([target], dev)[0]
    heap = [(h0, 0, key(target), target, ())]
    seen = {key(target)}
    exp = 0
    while heap and exp < cap:
        _pri, gc, k, st, prog = heapq.heappop(heap)
        if k == ik:
            return True, exp, gc
        if gc >= MAXM:
            continue
        exp += 1
        kids = [compose(inv_tabs[p], st) for p in range(len(NAMES))]   # r' = r . p^-1  (apply p^-1 first, then r)
        hs = hfn(kids, dev)
        for p, kid in enumerate(kids):
            kk = key(kid)
            if kk in seen:
                continue
            seen.add(kk)
            heapq.heappush(heap, (gc + 1 + lam * hs[p], gc + 1, kk, kid, prog + (p,)))
    return False, exp, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n_train", type=int, default=1200)
    ap.add_argument("--held", type=int, default=400)
    ap.add_argument("--steps", type=int, default=6000)
    ap.add_argument("--batch", type=int, default=512)
    ap.add_argument("--demos", type=int, default=8)
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--lam", type=float, default=2.0)
    ap.add_argument("--cap", type=int, default=400)
    ap.add_argument("--eval_cap", type=int, default=120)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    torch.manual_seed(args.seed)

    probe, table = cayley(dev, args.seed)
    progs = [w for w in table.values() if 0 < len(w) <= MAXM]
    print(f"device {dev} | group order 7200 | universe depth<={MAXM}: {len(progs)} transformations")

    # Canonical tables for every primitive and their inverses, ASSERTED against the reference action.
    prim_tabs = [(compile_progs([(p,)], dev)[0][0], compile_progs([(p,)], dev)[1][0]) for p in range(len(NAMES))]
    inv_tabs = [inverse(t) for t in prim_tabs]
    ident = (torch.arange(L, device=dev), torch.arange(V, device=dev))
    gchk = torch.Generator(device=dev).manual_seed(5)
    s = torch.randint(0, V, (32, L), generator=gchk, device=dev)
    for p in range(len(NAMES)):
        assert torch.equal(act(prim_tabs[p], s), apply_prog(s, (p,))), f"canonical table wrong for {NAMES[p]}"
        assert torch.equal(act(inv_tabs[p], act(prim_tabs[p], s)), s), f"inverse wrong for {NAMES[p]}"
        assert torch.equal(act(compose(prim_tabs[p], inv_tabs[p]), s), s), "compose/inverse disagree"
    # compose must match sequential application, in the right order.
    a, b = prim_tabs[0], prim_tabs[6]
    assert torch.equal(act(compose(a, b), s), act(b, act(a, s))), "compose has its operands the wrong way round"
    print("canonical tables, inverses and composition verified against the reference action")

    # EXACT RECOVERY from demonstrations, measured on the held-out functions.
    affines = []
    for sgn in (1, -1):
        for c in range(V):
            affines.append(((sgn * torch.arange(V, device=dev) + c) % V))
    g = torch.Generator().manual_seed(args.seed)
    by = collections.defaultdict(list)
    for w in progs:
        by[len(w)].append(w)
    held, pool = [], []
    frac = args.held / len(progs)
    for d, ws in sorted(by.items()):
        order = torch.randperm(len(ws), generator=g).tolist()
        cut = min(len(ws) - 1, max(3, int(round(frac * len(ws)))))
        held += [ws[i] for i in order[:cut]]
        pool += [ws[i] for i in order[cut:]]
    order = torch.randperm(len(pool), generator=g).tolist()
    train = [pool[i] for i in order][:args.n_train]

    gr = torch.Generator(device=dev).manual_seed(3)
    xs = torch.randint(0, V, (args.demos, L), generator=gr, device=dev)
    ok = 0
    for w in stratify(held, 120):
        t = recover(xs, apply_prog(xs, w), affines, dev)
        ok += int(t is not None and torch.equal(act(t, xs), apply_prog(xs, w)))
    print(f"canonical form recovered from {args.demos} demonstrations on {ok}/{len(stratify(held, 120))} held-out "
          f"functions (exact, brute-forcing the {len(affines)} affine value maps)")
    print(f"heuristic trained on {len(train)} transformations | {len(held)} held out | state = {L + V} tokens\n")

    tabs = compile_progs(train, dev)
    lens = torch.tensor([len(w) for w in train], device=dev)
    model = Model(max_len=L + V + 2, pos="rope", n_vocab=N_VOCAB).to(dev)
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.01, betas=(0.9, 0.98),
                            fused=(dev == "cuda"))
    warm = args.steps // 20
    sched = torch.optim.lr_scheduler.LambdaLR(
        opt, lambda s_: (s_ + 1) / max(1, warm) if s_ < warm
        else 0.5 * (1 + math.cos(math.pi * (s_ - warm) / (args.steps - warm))))
    trainer = torch.compile(model) if dev == "cuda" else model
    gg = torch.Generator(device=dev).manual_seed(args.seed)
    t0 = time.time()
    for _ in range(args.steps):
        tok = make(args.batch, tabs, lens, dev, gg)
        with torch.autocast("cuda", dtype=torch.bfloat16, enabled=(dev == "cuda")):
            logits = trainer(tok)[:, -2]
        loss = F.cross_entropy(logits.float(), tok[:, -1])
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        sched.step()
    print(f"heuristic trained in {time.time() - t0:.0f}s | final loss {loss.item():.4f}")

    @torch.no_grad()
    def quality(ws):
        tb, ln = compile_progs(ws, dev), torch.tensor([len(w) for w in ws], device=dev)
        idx_t, vmp_t = tb
        toks = torch.cat([idx_t + IDX0, vmp_t + VMP0], dim=1)
        pred = model(toks)[:, -1, DIST0:DIST0 + MAXM + 1].argmax(-1).float()
        return (pred == ln.float()).float().mean().item(), (pred - ln.float()).abs().mean().item()
    tr = quality(stratify(train, 150))
    he = quality(stratify(held, 150))
    print(f"\nHEURISTIC QUALITY (depth-stratified)   train exact {tr[0]:.3f} MAE {tr[1]:.2f}   "
          f"HELD-OUT exact {he[0]:.3f} MAE {he[1]:.2f}   (chance exact ~{1 / (MAXM + 1):.3f})")
    print(f"   behavioural version (costtogo.py) for comparison:  train exact 0.238 MAE 1.62   "
          f"HELD-OUT exact 0.276 MAE 1.38")

    tasks = stratify(held, args.eval_cap)
    tab_of = {}
    for w in tasks:
        it, vt = compile_progs([w], dev)
        tab_of[w] = (it[0], vt[0])
    print(f"\nSEARCH on {len(tasks)} HELD-OUT transformations | weighted A*, lam={args.lam}, cap={args.cap}")
    print(f"{'heuristic':<12}{'found':>8}{'expansions':>12}{'exp (solved)':>14}{'optimal':>9}")
    for label, hfn in (("zero", h_zero), ("misplaced", h_misplaced),
                       ("learned", lambda st, d: h_learned(model, st, d))):
        rs = [best_first(tab_of[w], inv_tabs, hfn, ident, dev, args.lam, args.cap) for w in tasks]
        solved = [(r[1], r[2], len(w)) for r, w in zip(rs, tasks) if r[0]]
        opt_rate = (sum(1 for e, gc, dl in solved if gc == dl) / len(solved)) if solved else float("nan")
        print(f"{label:<12}{sum(r[0] for r in rs) / len(rs):>8.3f}{sum(r[1] for r in rs) / len(rs):>12.1f}"
              f"{(sum(e for e, _, _ in solved) / len(solved) if solved else float('nan')):>14.1f}{opt_rate:>9.3f}")
    print("\n'optimal' = the found program had MINIMAL length (weighted A* is not admissible at lam>1, so this can drop).")
    print("CLAIM: learned << misplaced << zero on expansions at equal found. If learned ~ misplaced, the network")
    print("contributed nothing over a free hand-coded proxy -- which is what happened in the BEHAVIOURAL version.")


if __name__ == "__main__":
    main()
